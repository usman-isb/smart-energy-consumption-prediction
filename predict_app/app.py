"""
Electricity Consumption Predictor
Smart Energy Consumption Forecasting

Standalone web app. Run with:
    streamlit run app.py

Requires (generated by notebooks/06_best_model.ipynb):
    models/rf_pjm.pkl
    data/processed/pjm_scaler.pkl
    data/processed/pjm_processed.csv
"""

import streamlit as st
import pandas as pd
import numpy as np
import pickle
import os
import plotly.graph_objects as go
from datetime import datetime, date, time

# ── Paths ─────────────────────────────────────────────────────────────────────
BASE        = os.path.join(os.path.dirname(__file__), '..')
MODEL_PATH  = os.path.join(BASE, 'models', 'rf_pjm.pkl')
SCALER_PATH = os.path.join(BASE, 'data', 'processed', 'pjm_scaler.pkl')
DATA_PATH   = os.path.join(BASE, 'data', 'processed', 'pjm_processed.csv')

MONTH_NAMES = ["January","February","March","April","May","June",
               "July","August","September","October","November","December"]
DAY_NAMES   = ["Monday","Tuesday","Wednesday","Thursday","Friday","Saturday","Sunday"]

# ── Page config ───────────────────────────────────────────────────────────────
st.set_page_config(
    page_title="Electricity Consumption Predictor",
    page_icon="⚡",
    layout="centered"
)

# ── Load resources ─────────────────────────────────────────────────────────────
@st.cache_resource
def load_model():
    with open(MODEL_PATH, 'rb') as f:
        return pickle.load(f)

@st.cache_resource
def load_scaler():
    with open(SCALER_PATH, 'rb') as f:
        return pickle.load(f)

@st.cache_data
def load_data():
    df = pd.read_csv(DATA_PATH, index_col='Datetime', parse_dates=True)
    return df

# ── Check required files ───────────────────────────────────────────────────────
missing = []
if not os.path.exists(MODEL_PATH):  missing.append('models/rf_pjm.pkl')
if not os.path.exists(SCALER_PATH): missing.append('data/processed/pjm_scaler.pkl')
if not os.path.exists(DATA_PATH):   missing.append('data/processed/pjm_processed.csv')

# ── Header ─────────────────────────────────────────────────────────────────────
st.title("⚡ Electricity Consumption Predictor")
st.caption("Smart Energy Consumption Forecasting | Model: Random Forest (R² = 0.9962)")
st.markdown("---")

with st.expander("ℹ️ What does this app do?", expanded=False):
    st.markdown("""
    This app uses a trained **Random Forest model** to predict electricity consumption
    for the **PJM East regional grid** (eastern United States, serving tens of millions of people).

    **Two modes are available:**

    🔵 **Historical Prediction** — Pick any date from 2015–2018 (the test period).
    The app uses the real 24 hours before that point as model input and shows how
    accurately the model predicts that specific hour.

    🟠 **Future Forecast** — Pick any future year, month, and day type.
    The app builds a typical 24-hour demand profile from matching historical days
    and uses the model to predict what electricity consumption would look like on
    that type of day in the future.

    **Key terms:**
    | Term | Meaning |
    |------|---------|
    | MW (Megawatt) | Unit of electricity — 1 MW powers roughly 400–1,000 homes |
    | Typical demand | 19,000 MW (quiet night) to 65,000 MW (hot summer afternoon) |
    | R² = 0.9962 | The model explains 99.62% of all variation in electricity demand |
    | Error % | How far off the prediction is — below 2% is excellent |
    """)

st.markdown("---")

if missing:
    st.error("**Required files not found. Run notebook first.**")
    st.markdown("Open and run **`notebooks/06_best_model.ipynb`** to generate:")
    for f in missing:
        st.markdown(f"- `{f}`")
    st.stop()

model  = load_model()
scaler = load_scaler()
df     = load_data()

split_idx  = int(len(df) * 0.8)
test_start = df.index[split_idx].date()
max_date   = df.index.max().date()

# ── Tabs ───────────────────────────────────────────────────────────────────────
tab1, tab2 = st.tabs(["🔵 Historical Prediction", "🟠 Future Forecast"])

# ═══════════════════════════════════════════════════════════════════════════════
# TAB 1 — HISTORICAL PREDICTION
# ═══════════════════════════════════════════════════════════════════════════════
with tab1:
    st.subheader("Predict a specific historical hour")
    st.markdown(
        f"Choose any date between **{test_start}** and **{max_date}** — "
        "the test period (data the model never saw during training). "
        "The app uses the real 24 hours before your selected time as model input."
    )

    col1, col2 = st.columns([2, 1])
    with col1:
        selected_date = st.date_input(
            "📅 Date",
            value=test_start,
            min_value=test_start,
            max_value=max_date,
            help="Pick any date from 2015–2018"
        )
    with col2:
        selected_hour = st.slider(
            "🕐 Hour of day",
            min_value=0, max_value=23, value=12,
            format="%d:00",
            help="0 = midnight · 12 = noon · 23 = 11 PM"
        )

    if st.button("⚡ Predict", use_container_width=True, type="primary", key="hist_btn"):
        target_dt = pd.Timestamp(datetime.combine(selected_date, time(selected_hour)))

        if target_dt not in df.index:
            st.warning(f"No data found for {target_dt}. Try a nearby date or hour.")
            st.stop()

        pos = df.index.get_loc(target_dt)
        if pos < 24:
            st.warning("Not enough history before this timestamp. Please select a later date.")
            st.stop()

        window_idx  = df.index[pos - 24 : pos]
        window_vals = df.loc[window_idx, 'PJME_MW_scaled'].values
        window_mw   = df.loc[window_idx, 'PJME_MW'].values

        pred_scaled = model.predict(window_vals.reshape(1, -1))[0]
        pred_mw     = scaler.inverse_transform([[pred_scaled]])[0][0]
        actual_mw   = df.loc[target_dt, 'PJME_MW']
        error_mw    = abs(pred_mw - actual_mw)
        error_pct   = error_mw / actual_mw * 100

        st.markdown("---")
        st.subheader(f"📊 Result for {target_dt.strftime('%A, %d %B %Y — %H:00')}")
        st.caption("The model was given the 24 hours before this timestamp and predicted demand for this hour.")

        m1, m2, m3, m4 = st.columns(4)
        m1.metric("Predicted", f"{pred_mw:,.0f} MW",
                  help="What the Random Forest model predicted")
        m2.metric("Actual",    f"{actual_mw:,.0f} MW",
                  help="Real recorded demand for this hour")
        m3.metric("Error",     f"{error_mw:,.0f} MW",
                  help="Absolute difference between predicted and actual")
        m4.metric("Error %",   f"{error_pct:.2f}%",
                  help="Error as % of actual — below 2% is excellent")

        fig = go.Figure()
        fig.add_trace(go.Scatter(
            x=window_idx, y=window_mw,
            mode='lines+markers', name='Actual — 24h input',
            line=dict(color='#2196F3', width=2), marker=dict(size=5)
        ))
        fig.add_trace(go.Scatter(
            x=[target_dt], y=[pred_mw], mode='markers',
            name=f'Predicted ({pred_mw:,.0f} MW)',
            marker=dict(color='#FF9800', size=14, symbol='star')
        ))
        fig.add_trace(go.Scatter(
            x=[target_dt], y=[actual_mw], mode='markers',
            name=f'Actual ({actual_mw:,.0f} MW)',
            marker=dict(color='#4CAF50', size=14, symbol='circle')
        ))
        fig.update_layout(
            title="24-Hour Input Window + Prediction",
            xaxis_title="Time", yaxis_title="Electricity Demand (MW)",
            legend=dict(orientation='h', y=-0.25),
            height=420, margin=dict(t=50, b=70, l=60, r=20),
            plot_bgcolor='rgba(0,0,0,0)', paper_bgcolor='rgba(0,0,0,0)',
            xaxis=dict(showgrid=True, gridcolor='rgba(128,128,128,0.2)'),
            yaxis=dict(showgrid=True, gridcolor='rgba(128,128,128,0.2)')
        )
        st.plotly_chart(fig, use_container_width=True)
        st.caption(
            "🔵 Blue line = 24 hours of actual data fed to the model  |  "
            "🟠 Orange star = model prediction  |  🟢 Green dot = actual recorded value"
        )

        if error_pct < 2:
            quality, colour = "Excellent prediction", "green"
            note = "Within 2% of actual demand — performing at research benchmark level."
        elif error_pct < 5:
            quality, colour = "Good prediction", "orange"
            note = "Within 5% of actual demand — acceptable for real-world use."
        else:
            quality, colour = "High error — unusual demand event", "red"
            note = "Above 5% error — typically caused by extreme weather or holidays."

        st.markdown(f"**Verdict:** :{colour}[{quality}]")
        st.markdown(
            f"The model predicted **{pred_mw:,.0f} MW** vs actual **{actual_mw:,.0f} MW** "
            f"— error of **{error_mw:,.0f} MW ({error_pct:.2f}%)**. {note}"
        )

        with st.expander("📖 How to read these numbers"):
            st.markdown(f"""
            - **{pred_mw:,.0f} MW (Predicted):** The model analysed the last 24 hours and
              estimated this hour would need {pred_mw:,.0f} megawatts.
            - **{actual_mw:,.0f} MW (Actual):** The real demand recorded by PJM East.
            - **{error_mw:,.0f} MW error ({error_pct:.2f}%):** The model was off by
              {error_mw:,.0f} MW. Typical total demand is 40,000–50,000 MW, so
              this represents {error_pct:.2f}% of the actual value.
            - **The blue line** is what the model was given as input — 24 consecutive hours.
            - **Orange star vs green dot** — the closer they are, the better the prediction.
            """)

        st.info(
            "💡 **Tip:** Try a weekday afternoon in July (peak summer demand) "
            "or a Sunday night in April (lowest demand of the year)."
        )

# ═══════════════════════════════════════════════════════════════════════════════
# TAB 2 — FUTURE FORECAST
# ═══════════════════════════════════════════════════════════════════════════════
with tab2:
    st.subheader("Forecast a future day's demand profile")
    st.markdown("""
    Select a **future year**, **month**, and **day type**.
    The app finds all historical days from 2002–2018 with the same month and day type,
    builds a typical 24-hour demand profile from them, and uses the model to predict
    what electricity consumption would look like on that type of day.
    """)

    with st.expander("ℹ️ How does this work?", expanded=False):
        st.markdown("""
        **Why we use historical patterns:**

        The model needs 24 hours of actual electricity data as input. Since we have no
        real data beyond January 2018, we use the **average demand profile** from
        matching historical days as a stand-in input.

        **Steps the app takes:**
        1. Finds all historical days matching your selected month + day type (e.g. all July Mondays from 2002–2018)
        2. Computes the **average 24-hour demand** for those days (the blue band shows the range)
        3. Uses the average profile from the **previous day type** as the starting 24-hour input window
        4. Runs the model **hour by hour** through the selected day (each predicted hour feeds the next)
        5. Shows the model's predicted 24-hour demand curve for that type of day

        **What the year selection means:**

        The year does not change the underlying demand pattern — electricity consumption
        patterns (by season and day type) were stable from 2002–2018.
        The forecast represents what a **typical** day of that type would look like,
        projected into the selected year based on historical behaviour.

        **Honest limitation:** This is a pattern projection, not a true multi-year forecast.
        It does not account for future changes in population, economy, or technology.
        It is valid for demonstrating what the model predicts based on learned patterns.
        """)

    col1, col2, col3 = st.columns(3)
    with col1:
        future_year = st.selectbox(
            "📅 Year",
            list(range(2019, 2036)),
            index=0,
            help="Any year from 2019 onward — based on historical 2002–2018 patterns"
        )
    with col2:
        future_month = st.selectbox(
            "📆 Month",
            list(range(1, 13)),
            format_func=lambda x: MONTH_NAMES[x - 1],
            index=6,
            help="Month of the year"
        )
    with col3:
        future_day_name = st.selectbox(
            "📋 Day type",
            DAY_NAMES,
            index=0,
            help="Day of the week"
        )
    future_dow = DAY_NAMES.index(future_day_name)

    if st.button("🔮 Generate Forecast", use_container_width=True, type="primary", key="future_btn"):

        # Get all historical days matching month + day type
        mask     = (df.index.month == future_month) & (df.index.dayofweek == future_dow)
        hist_df  = df[mask]

        if len(hist_df) < 48:
            st.warning(
                f"Not enough historical data for {future_day_name}s in {MONTH_NAMES[future_month-1]}. "
                "Try a different combination."
            )
            st.stop()

        # Hourly statistics for the selected day type
        hourly = hist_df.groupby(hist_df.index.hour)['PJME_MW'].agg(
            mean='mean', std='std', low='min', high='max'
        ).reindex(range(24))

        # Previous day type for building the initial 24h input window
        prev_dow  = (future_dow - 1) % 7
        prev_mask = (df.index.month == future_month) & (df.index.dayofweek == prev_dow)
        prev_df   = df[prev_mask]

        if len(prev_df) < 24:
            # fallback: use same day type
            prev_hourly_scaled = hist_df.groupby(hist_df.index.hour)['PJME_MW_scaled'].mean()
        else:
            prev_hourly_scaled = prev_df.groupby(prev_df.index.hour)['PJME_MW_scaled'].mean()

        # Build initial 24-hour window (scaled) from previous day averages
        init_window = np.array([
            prev_hourly_scaled.get(h, prev_hourly_scaled.mean()) for h in range(24)
        ])

        # Autoregressive prediction hour by hour through the selected day
        window = init_window.copy()
        preds_scaled = []
        for h in range(24):
            pred = model.predict(window.reshape(1, -1))[0]
            preds_scaled.append(pred)
            window = np.roll(window, -1)
            window[-1] = pred

        # Convert to MW
        preds_mw = scaler.inverse_transform(
            np.array(preds_scaled).reshape(-1, 1)
        ).flatten()

        hours       = list(range(24))
        hour_labels = [f"{h:02d}:00" for h in hours]

        st.markdown("---")
        st.subheader(
            f"📊 Forecast: {future_day_name}, {MONTH_NAMES[future_month-1]} {future_year}"
        )

        n_hist = mask.sum() // 24
        st.caption(
            f"Based on {n_hist} historical {future_day_name}s in {MONTH_NAMES[future_month-1]} "
            f"from 2002–2018. Shaded band = historical range (min–max). "
            f"Dashed line = historical average. Orange line = model prediction."
        )

        # ── Summary metrics ──────────────────────────────────────────────────
        peak_hour = int(np.argmax(preds_mw))
        low_hour  = int(np.argmin(preds_mw))

        m1, m2, m3, m4 = st.columns(4)
        m1.metric("Peak demand",     f"{preds_mw.max():,.0f} MW",
                  help=f"Highest predicted demand — at {peak_hour:02d}:00")
        m2.metric("Peak hour",       f"{peak_hour:02d}:00",
                  help="Hour of the day with highest predicted demand")
        m3.metric("Lowest demand",   f"{preds_mw.min():,.0f} MW",
                  help=f"Lowest predicted demand — at {low_hour:02d}:00")
        m4.metric("Daily average",   f"{preds_mw.mean():,.0f} MW",
                  help="Average demand across all 24 hours")

        # ── Chart ────────────────────────────────────────────────────────────
        fig = go.Figure()

        # Historical min–max band
        fig.add_trace(go.Scatter(
            x=hours + hours[::-1],
            y=list(hourly['high']) + list(hourly['low'][::-1]),
            fill='toself',
            fillcolor='rgba(33,150,243,0.08)',
            line=dict(color='rgba(0,0,0,0)'),
            name='Historical range (min–max)',
            hoverinfo='skip'
        ))

        # Historical ±1 std band
        fig.add_trace(go.Scatter(
            x=hours + hours[::-1],
            y=list(hourly['mean'] + hourly['std']) + list((hourly['mean'] - hourly['std'])[::-1]),
            fill='toself',
            fillcolor='rgba(33,150,243,0.18)',
            line=dict(color='rgba(0,0,0,0)'),
            name='Historical range (±1 std)',
            hoverinfo='skip'
        ))

        # Historical mean
        fig.add_trace(go.Scatter(
            x=hours,
            y=hourly['mean'],
            mode='lines',
            name='Historical average',
            line=dict(color='#2196F3', width=2, dash='dash')
        ))

        # Model prediction
        fig.add_trace(go.Scatter(
            x=hours,
            y=preds_mw,
            mode='lines+markers',
            name='Model prediction',
            line=dict(color='#FF9800', width=3),
            marker=dict(size=7, color='#FF9800')
        ))

        # Peak marker
        fig.add_trace(go.Scatter(
            x=[peak_hour], y=[preds_mw[peak_hour]],
            mode='markers+text',
            name=f'Peak ({preds_mw[peak_hour]:,.0f} MW)',
            marker=dict(color='#F44336', size=14, symbol='triangle-up'),
            text=[f"Peak\n{preds_mw[peak_hour]:,.0f} MW"],
            textposition='top center',
            showlegend=False
        ))

        fig.update_layout(
            title=f"24-Hour Demand Forecast — {future_day_name}, {MONTH_NAMES[future_month-1]} {future_year}",
            xaxis_title="Hour of day",
            yaxis_title="Electricity Demand (MW)",
            xaxis=dict(
                tickmode='array',
                tickvals=hours,
                ticktext=hour_labels,
                tickangle=-45
            ),
            legend=dict(orientation='h', y=-0.3),
            height=480,
            margin=dict(t=60, b=100, l=60, r=20),
            plot_bgcolor='rgba(0,0,0,0)',
            paper_bgcolor='rgba(0,0,0,0)',
            xaxis_showgrid=True,
            yaxis_showgrid=True,
            xaxis_gridcolor='rgba(128,128,128,0.15)',
            yaxis_gridcolor='rgba(128,128,128,0.15)'
        )

        st.plotly_chart(fig, use_container_width=True)

        # ── Hour-by-hour table ───────────────────────────────────────────────
        with st.expander("📋 Hour-by-hour breakdown"):
            table_df = pd.DataFrame({
                'Hour':             hour_labels,
                'Predicted (MW)':   [f"{v:,.0f}" for v in preds_mw],
                'Hist. Average (MW)': [f"{v:,.0f}" for v in hourly['mean']],
                'Difference (MW)':  [f"{p - h:+,.0f}" for p, h in zip(preds_mw, hourly['mean'])]
            })
            st.dataframe(table_df, use_container_width=True, hide_index=True)

        # ── Interpretation ───────────────────────────────────────────────────
        hist_mean = hourly['mean'].mean()
        diff_pct  = (preds_mw.mean() - hist_mean) / hist_mean * 100

        st.markdown(f"""
        **Reading the chart:**
        - The **orange line** is the model's hour-by-hour prediction for a typical
          {future_day_name} in {MONTH_NAMES[future_month-1]}
        - The **dashed blue line** is the straight historical average for that day type
        - The **shaded bands** show the range of demand seen across all historical
          {future_day_name}s in {MONTH_NAMES[future_month-1]} from 2002–2018
        - The model predicts a **daily average of {preds_mw.mean():,.0f} MW**,
          which is {abs(diff_pct):.1f}% {'above' if diff_pct > 0 else 'below'} the
          historical average of {hist_mean:,.0f} MW
        - **Peak demand** of {preds_mw.max():,.0f} MW is expected at **{peak_hour:02d}:00**
        """)

        st.info(
            f"💡 This forecast represents what a **typical {future_day_name} in "
            f"{MONTH_NAMES[future_month-1]}** would look like based on patterns "
            f"learned from {n_hist} historical days (2002–2018). "
            "It does not account for future economic or climate changes."
        )

# ── Footer ─────────────────────────────────────────────────────────────────────
st.markdown("---")
st.caption(
    "Model: Random Forest (n_estimators=100, random_state=42)  |  "
    "Dataset: PJM East regional grid, USA  |  "
    "Training: 2002–2015  |  Test: 2015–2018  |  "
    "Window: 24 hours"
)
